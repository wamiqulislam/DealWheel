-- ============================================================
-- Reference copy of the RAW listings table schema (source data,
-- populated by the scraper). Kept here so the whole DB schema is
-- versioned alongside the code that reads/writes it.
-- This file is documentation/reference -- run it only if the table
-- does not already exist in your database.
-- ============================================================

